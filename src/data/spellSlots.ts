/** Bonus spell slots from high ability score (PF1e standard table) */
export function getBonusSpells(abilityScore: number): number[] {
  const mod = Math.floor((abilityScore - 10) / 2);
  const bonus = Array(10).fill(0);
  for (let spellLvl = 1; spellLvl <= 9; spellLvl++) {
    const b = Math.max(0, Math.floor((mod - spellLvl + 1) / 4) + (mod >= spellLvl ? 1 : 0));
    // PF1e formula: bonus spell of level N if ability mod >= N, +1 slot per 4 mod above
    const val = mod >= spellLvl ? Math.floor((mod - spellLvl) / 4) + 1 : 0;
    bonus[spellLvl] = val;
  }
  return bonus;
}
